-- =====================================================================================
-- Migration for databases created BEFORE the extended features:
--   * tickets.resolved_at (resolution time statistics) tickets.due_date (optional deadline)
--     and tickets.version (optimistic locking)
--   * new status CANCELLED (check constraints must accept it)
--   * audit_log table
-- It is idempotent. Run it once against an existing database (pgAdmin Query Tool, or):
--   docker compose exec -T postgres sh -c 'psql -U "$POSTGRES_USER" -d "$POSTGRES_DB"' \
--     < carpeta_scripts/migrations/02_extended_features.sql
-- A brand-new database does not need it: 01_schema.sql already contains everything.
-- =====================================================================================

ALTER TABLE tickets ADD COLUMN IF NOT EXISTS resolved_at TIMESTAMPTZ;
ALTER TABLE tickets ADD COLUMN IF NOT EXISTS due_date DATE;
ALTER TABLE tickets ADD COLUMN IF NOT EXISTS version BIGINT NOT NULL DEFAULT 0;

-- Backfill: tickets that are already RESOLVED or CLOSED get the date of their last RESOLVED history entry.
UPDATE tickets t
   SET resolved_at = h.changed_at
  FROM (SELECT ticket_id, MAX(changed_at) AS changed_at
          FROM status_history
         WHERE new_status = 'RESOLVED'
         GROUP BY ticket_id) h
 WHERE h.ticket_id = t.id
   AND t.resolved_at IS NULL
   AND t.status IN ('RESOLVED', 'CLOSED');

-- Drop every check constraint that mentions a status column (Hibernate and 01_schema.sql use different names).
DO $$
DECLARE
    r RECORD;
BEGIN
    FOR r IN
        SELECT conrelid::regclass AS tbl, conname
          FROM pg_constraint
         WHERE contype = 'c'
           AND conrelid IN ('tickets'::regclass, 'status_history'::regclass)
           AND pg_get_constraintdef(oid) ILIKE '%status%'
    LOOP
        EXECUTE format('ALTER TABLE %s DROP CONSTRAINT %I', r.tbl, r.conname);
    END LOOP;
END $$;

ALTER TABLE tickets ADD CONSTRAINT ck_tickets_status
    CHECK (status IN ('OPEN', 'ASSIGNED', 'IN_PROGRESS', 'RESOLVED', 'CLOSED', 'CANCELLED'));
ALTER TABLE status_history ADD CONSTRAINT ck_history_previous
    CHECK (previous_status IS NULL
        OR previous_status IN ('OPEN', 'ASSIGNED', 'IN_PROGRESS', 'RESOLVED', 'CLOSED', 'CANCELLED'));
ALTER TABLE status_history ADD CONSTRAINT ck_history_new
    CHECK (new_status IN ('OPEN', 'ASSIGNED', 'IN_PROGRESS', 'RESOLVED', 'CLOSED', 'CANCELLED'));

CREATE TABLE IF NOT EXISTS audit_log (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    action       VARCHAR(40)  NOT NULL,
    entity_type  VARCHAR(30)  NOT NULL,
    entity_id    BIGINT,
    actor_id     BIGINT       NOT NULL,
    details      VARCHAR(500),
    created_at   TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    CONSTRAINT fk_audit_actor FOREIGN KEY (actor_id) REFERENCES users (id)
);
CREATE INDEX IF NOT EXISTS idx_audit_action ON audit_log (action);
CREATE INDEX IF NOT EXISTS idx_audit_entity ON audit_log (entity_type, entity_id);
